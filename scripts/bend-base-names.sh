#!/usr/bin/env bash
# The top-level names of Bend's Base (docs/08-bend/02-phase-1-parsing.md S-BD3, Q-BD3: a generated list committed in bend-analysis).
#   scripts/bend-base-names.sh <path to the bend clone>            print src/base_names.rs
#   scripts/bend-base-names.sh <path to the bend clone> --write    write it: languages/bend/crates/bend-analysis/src/base_names.rs
#   scripts/bend-base-names.sh <path to the bend clone> --list     print `<kind> <name>`, kind one of def, type, law, ctr, sorted bytewise
# Only this script writes the file; the crate never does. The pin in the file's first lines is the clone's HEAD (the clone is the pin, ENGINE.md), and
# bend-analysis has an ignored test, `base_names_are_current` (BEND_CLONE=<clone>), that runs this script and fails when the committed file differs.
# Names are found with a regex: `^(@unsafe )?def NAME`, `^type NAME`, `^law NAME`, and the constructor lines (`  NAME{`) indented under a type. Checked
# against Bend's own loader on 2026-11-20: the same 517 distinct top-level names (541 declarations: 24 laws that Base itself proves) and 50 constructors.
set -euo pipefail
export LC_ALL=C
root="$(cd "$(dirname "$0")/.." && pwd)"
[ $# -ge 1 ] && [ $# -le 2 ] || { echo "usage: scripts/bend-base-names.sh <path to the bend clone> [--write|--list]" >&2; exit 2; }
clone="$(cd "$1" && pwd)"
mode="${2:-}"
case "$mode" in ""|--write|--list) ;; *) echo "unknown option $mode" >&2; exit 2 ;; esac
base="$clone/bend2/base.bend"
[ -f "$base" ] || { echo "no $base" >&2; exit 2; }

# a name is letters, digits, `_` and `.` (bend.ts char_is_name); a def's `?` and `(` end it
list() {
  awk '
    /^[^ \t#]/ { in_type = 0 }
    match($0, /^(@unsafe )?def [A-Za-z_][A-Za-z0-9_.]*/) { n = substr($0, RSTART, RLENGTH); sub(/^(@unsafe )?def /, "", n); print "def " n; next }
    match($0, /^type [A-Za-z_][A-Za-z0-9_.]*/)           { n = substr($0, RSTART + 5, RLENGTH - 5); print "type " n; in_type = 1; next }
    match($0, /^law [A-Za-z_][A-Za-z0-9_.]*/)            { n = substr($0, RSTART + 4, RLENGTH - 4); print "law " n; next }
    in_type && match($0, /^[ \t]+[A-Za-z_][A-Za-z0-9_.]*\{/) { n = substr($0, RSTART, RLENGTH - 1); gsub(/[ \t]/, "", n); print "ctr " n }
  ' "$base" | sort
}

source_file() {
  local pin lines
  pin="$(git -C "$clone" log -1 --format=%h 2>/dev/null || echo unknown)"
  lines="$(wc -l < "$base" | tr -d ' ')"
  echo "//! Base's top-level names. GENERATED by scripts/bend-base-names.sh from bend $pin (bend2/base.bend, $lines lines): do not edit."
  echo "//! Regenerate with \`scripts/bend-base-names.sh <bend clone> --write\` when the grammar pin moves (languages/bend/ENGINE.md)."
  echo
  echo "/// The \`def\`, \`type\` and \`law\` names, each once, sorted bytewise (so \`binary_search\` finds one). A law and the def that proves it share a name."
  echo "pub(crate) static TLDS: &[&str] = &["
  list | awk '$1 != "ctr" { print $2 }' | sort -u | sed 's/.*/    "&",/'
  echo "];"
  echo
  echo "/// The constructor names, sorted bytewise."
  echo "pub(crate) static CTRS: &[&str] = &["
  list | awk '$1 == "ctr" { print $2 }' | sort -u | sed 's/.*/    "&",/'
  echo "];"
}

case "$mode" in
  --list) list ;;
  --write)
    out="$root/languages/bend/crates/bend-analysis/src/base_names.rs"
    tmp="$(mktemp)"
    source_file > "$tmp"
    mv "$tmp" "$out"
    echo "wrote $out"
    ;;
  *) source_file ;;
esac
